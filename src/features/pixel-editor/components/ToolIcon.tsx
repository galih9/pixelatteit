type Run = { x: number; y: number; length: number };

function toRuns(rows: Array<string>): Array<Run> {
	const runs: Array<Run> = [];
	rows.forEach((row, y) => {
		let start = -1;
		for (let x = 0; x <= row.length; x++) {
			const filled = row[x] === "#";
			if (filled && start < 0) start = x;
			if (!filled && start >= 0) {
				runs.push({ x: start, y, length: x - start });
				start = -1;
			}
		}
	});
	return runs;
}

const RUNS: Record<Tool, Array<Run>> = Object.fromEntries(
	Object.entries(ICONS).map(([key, rows]) => [key, toRuns(rows)])
) as Record<Tool, Array<Run>>;

type ToolIconProps = { tool: Tool; className?: string };

export const ToolIcon = ({
	tool,
	className,
}: ToolIconProps): FunctionComponent => (
	<svg
		aria-hidden="true"
		className={className}
		fill="currentColor"
		shapeRendering="crispEdges"
		viewBox="0 0 12 12"
	>
		{RUNS[tool].map((run) => (
			<rect
				key={`${run.x}-${run.y}`}
				height={1}
				width={run.length}
				x={run.x}
				y={run.y}
			/>
		))}
	</svg>
);
